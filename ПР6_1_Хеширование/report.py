def block(path, start, end=None, strip=0):
    """Вырезать фрагмент вывода программы между маркерами."""
    t = open(path, encoding='utf-8').read()
    i = t.index(start)
    j = t.index(end, i) if end else len(t)
    return t[i:j].strip('\n')

