def out(path, start=None, end=None):
    t = open(path, encoding='utf-8').read()
    i = t.index(start) if start else 0
    j = t.index(end, i) if end else len(t)
    return t[i:j].strip('\n')

def src(f, start, end=None):
    t = open(f, encoding='utf-8').read()
    i = t.index(start)
    j = t.index(end, i) if end else t.index('\n    }\n', i) + 6
    return t[i:j].rstrip('\n')

